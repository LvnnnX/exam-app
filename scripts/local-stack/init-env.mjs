// Creates .env.local for the LOCAL stack only. Never prints secrets.
import { existsSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { ENV_PATH, GATEWAY_PORT, PG } from './env.mjs';
import { signJwt } from './jwt.mjs';

if (existsSync(ENV_PATH)) {
  console.log('.env.local sudah ada, tidak ditimpa.');
  process.exit(0);
}

const secret = randomBytes(48).toString('base64url');
const tenYears = Math.floor(Date.now() / 1000) + 10 * 365 * 24 * 3600;
const anon = signJwt({ role: 'anon', iss: 'local-stack', exp: tenYears }, secret);
const service = signJwt({ role: 'service_role', iss: 'local-stack', exp: tenYears }, secret);

const lines = [
  '# LOCAL ONLY. Generated by scripts/local-stack/init-env.mjs. Do not commit.',
  `NEXT_PUBLIC_SUPABASE_URL=http://127.0.0.1:${GATEWAY_PORT}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}`,
  `SUPABASE_SERVICE_ROLE_KEY=${service}`,
  `LOCAL_JWT_SECRET=${secret}`,
  `LOCAL_DATABASE_URL=postgres://${PG.user}@${PG.host}:${PG.port}/${PG.database}`,
  'LOCAL_ADMIN_EMAIL=admin@local.test',
  `LOCAL_ADMIN_PASSWORD=${randomBytes(12).toString('base64url')}`,
  '',
];
writeFileSync(ENV_PATH, lines.join('\n'), { mode: 0o600 });
console.log('.env.local dibuat (isi tidak ditampilkan). Password admin lokal ada di LOCAL_ADMIN_PASSWORD.');
